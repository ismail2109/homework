// ЗАДАНИЕ 10: Функция с map() и свойством isRare
// Логика: если год > 2000, то isRare = true
// ==========================================
function markRareBooks(bookArray) {
  return bookArray.map(book => {
    return {
      ...book,
      isRare: book.year > 2000
    };
  });
}